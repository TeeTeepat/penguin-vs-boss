export function t(lang, key, vars) {
  const d = dict[lang] || dict.th;
  let s = d[key] !== undefined ? d[key] : dict.th[key];
  if (s === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
